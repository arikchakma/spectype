function* blockScalarGrid() {
  const headers = ["|", ">", "|-", ">-", "|+", ">+", "|1", ">2", "|2-", ">1+", "|-1", ">+3"];
  const bodies = [
    ["x"],
    ["x", "y"],
    ["x", "", "y"],
    ["x", "", "", "y", ""],
    ["", "x"],
    [" x", "y"],
    ["x", " y", "z"],
    ["x", " y", "", " z", "w"],
    ["x", "  ", "y"],
    ["x", "", ""],
    ["  x", " y"],
    ["x  ", "y\t"],
    ["\tx", "y"],
    [""],
    [],
  ];
  const tails = ["", "\nnext: 1", "\n# c", "\n  # c", "\n...", "\n---"];
  for (const h of headers) {
    for (const b of bodies) {
      for (const indent of ["  ", "    ", " "]) {
        for (const tail of tails) {
          const body = b.map((l) => (l === "" ? "" : indent + l)).join("\n");
          yield `a: ${h}\n${body}${b.length ? "\n" : ""}${tail.slice(1)}${tail ? "\n" : ""}`;
          yield `- ${h}\n${body}${b.length ? "\n" : ""}${tail.slice(1)}${tail ? "\n" : ""}`;
        }
      }
    }
  }
}

function* scalarGrid() {
  const values = [
    "x",
    "x y",
    "x  y",
    "x\n  y",
    "x\n\n  y",
    "x\n  \n  y",
    "x \n  y",
    "x\n    y\n  z",
    "",
    " x",
    "x ",
    "x#y",
    "x #y",
    "x: y",
    "x:y",
    "x,y",
    "x]y",
    "x}y",
    "[x]",
    "{x}",
    "-x",
    "- x",
    "?x",
    "? x",
    ":x",
    "x\\ny",
    "x\\\n  y",
    "x''y",
    "x'y",
    'x"y',
    "x\\\"y",
    "\\u0041\\x41",
  ];
  for (const v of values) {
    yield `a: ${v}\n`;
    yield `a: '${v}'\n`;
    yield `a: "${v}"\n`;
    yield `- ${v}\n`;
    yield `[${v}]\n`;
    yield `{a: ${v}}\n`;
    yield `{${v}: 1}\n`;
    yield `${v}: 1\n`;
    yield `- '${v}'\n- "${v}"\n`;
  }
}

function* nestingGrid() {
  for (const n of [99, 100, 101, 499, 998, 999, 1000, 1001, 1200]) {
    yield "[".repeat(n) + "]".repeat(n) + "\n";
    yield "{a: ".repeat(n) + "1" + "}".repeat(n) + "\n";
    let s = "";
    for (let i = 0; i < n; i++) s += " ".repeat(i) + "a:\n";
    yield s + " ".repeat(n) + "x\n";
    s = "";
    for (let i = 0; i < n; i++) s += " ".repeat(i * 2) + "-\n";
    yield s;
    yield "- ".repeat(n) + "x\n";
  }
}

function* aliasGrid() {
  let s = "a0: &a0 [x, x]\n";
  for (let i = 1; i < 12; i++) s += `a${i}: &a${i} [*a${i - 1}, *a${i - 1}]\n`;
  yield s;
  s = "a0: &a0 {k: [1, 2, 3]}\n";
  for (let i = 1; i < 6; i++) s += `a${i}: &a${i}\n  <<: *a${i - 1}\n  k${i}: *a${i - 1}\n`;
  yield s;
  let merge = "base: &b {";
  for (let i = 0; i < 5000; i++) merge += `k${i}: ${i}, `;
  merge += "z: 0}\n";
  yield merge + "m1:\n  <<: *b\nm2:\n  <<: *b\n";
  yield merge + "m1:\n  <<: *b\n";
  yield "m:\n  <<: [" + Array.from({ length: 101 }, () => "{}").join(", ") + "]\n";
  yield "m:\n  <<: [" + Array.from({ length: 100 }, () => "{}").join(", ") + "]\n";
}

function* lineEndingVariants(cases) {
  for (const c of cases) {
    yield c.replace(/\n/g, "\r\n");
    yield c.replace(/\n/g, "\r");
    yield c.replace(/\n$/, "");
    yield "\ufeff" + c;
  }
}

export function adversarial() {
  const grids = [...blockScalarGrid(), ...scalarGrid()];
  return [
    ...HAND,
    ...grids,
    ...lineEndingVariants([...HAND, ...grids]),
    ...nestingGrid(),
    ...aliasGrid(),
  ];
}
