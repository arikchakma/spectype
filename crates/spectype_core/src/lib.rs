//! Generate TypeScript types from `OpenAPI` 3.0 / 3.1 documents.
//!
//! The output is byte-for-byte what `openapi-typescript@7.13.0` prints, so code written against
//! its `paths`, `components` and `operations` types (for example with `openapi-fetch`) keeps
//! compiling. See `COMPAT.md` for the known differences.
//!
//! The public facade over the pipeline: parse ([`spectype_document`]), lint and bundle
//! ([`spectype_redocly`]), transform and print ([`spectype_codegen`]).

pub use spectype_codegen::{
    Fix, Fixes, FsHost, HookContext, Host, LoadedDocument, Options, PropertyHookInput, TransformResult, UnknownFix,
    host, load_file, ts,
};
pub use spectype_document::{Error, Format, HostError, JsonPointer, Result, Value, parse, parse_document, value};
pub use spectype_redocly::{http, lint};

use spectype_codegen::{scan_discriminators, transform_document};

/// The header openapi-typescript prepends to every generated file.
pub const COMMENT_HEADER: &str =
    "/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n";

/// The generated source plus any warnings openapi-typescript would also have printed.
#[derive(Debug)]
pub struct Output {
    /// The generated file, header included.
    pub code: String,
    /// Warnings, in the order openapi-typescript prints them.
    pub warnings: Vec<String>,
}

/// Generates TypeScript from a parsed single-file document.
pub fn generate(document: Value, options: &Options) -> Result<Output> {
    generate_with_source(document, None, options)
}

/// Generates TypeScript from a parsed document read from `source`, so relative `$ref`s to other
/// files resolve against it.
pub fn generate_with_source(document: Value, source: Option<&std::path::Path>, options: &Options) -> Result<Output> {
    let source = source.map(|p| p.to_string_lossy());
    generate_with_host(document, source.as_deref(), options, &mut FsHost)
}

/// Generates TypeScript, loading referenced documents and running hooks through `host`.
///
/// `source` is the document's own location, a file path (relative to the working directory) or
/// an `http(s)` URL; relative `$ref`s resolve against it. Without one the document is treated
/// like openapi-typescript treats stdin: as located in the working directory.
pub fn generate_with_host(
    document: Value,
    source: Option<&str>,
    options: &Options,
    host: &mut dyn Host,
) -> Result<Output> {
    generate_retained(document, source, options, host).map(|(output, _)| output)
}

/// Like [`generate_with_host`], but also hands back the bundled document and the syntax tree, so
/// a caller that exits right after can skip freeing them.
pub fn generate_retained(
    mut document: Value,
    source: Option<&str>,
    options: &Options,
    host: &mut dyn Host,
) -> Result<(Output, impl Sized)> {
    parse::check_version(&document)?;
    let lint_warnings = spectype_redocly::bundle(&mut document, source, &mut |r| host.load(r), &options.lint)?;
    let (discriminators, scan_warnings) = scan_discriminators(&mut document);
    let mut warnings: Vec<String> = lint_warnings.iter().map(ToString::to_string).collect();
    warnings.extend(scan_warnings);
    let (stmts, transform_warnings) = match transform_document(&document, options, &discriminators, host) {
        Ok(done) => done,
        Err(e) if lint_warnings.is_empty() => return Err(e),
        Err(e) => {
            // The lint warnings were already "printed" upstream, before generation failed.
            let mut problems = lint_warnings;
            problems.push(lint::Problem { rule: String::new(), error: true, message: e.to_string(), pointer: None });
            return Err(Error::Lint(problems));
        }
    };
    warnings.extend(transform_warnings);
    let mut code = ts::print_into(String::from(COMMENT_HEADER), &stmts);
    if code.as_bytes().contains(&0xf4) && code.chars().any(|c| value::lone_surrogate(c).is_some()) {
        code = code.chars().map(|c| if value::lone_surrogate(c).is_some() { '\u{fffd}' } else { c }).collect();
    }
    Ok((Output { code, warnings }, (document, stmts)))
}

/// Parses `source` (JSON or YAML) and generates TypeScript.
pub fn generate_from_str(source: &str, options: &Options) -> Result<Output> {
    generate(parse_document(source, Format::Auto)?, options)
}
